import { env } from '../config/env.js';
const json = (schema: unknown) => ({ content: { 'application/json': { schema } } });
const ref = (name: string) => ({ $ref: '#/components/schemas/' + name });
const error = (code: number) => ({ description: 'Respuesta HTTP ' + code, ...json(ref('ErrorEnvelope')) });
const security = [{ bearerAuth: [] }];
const taskResponses = { '401': error(401), '422': error(422) };
export const openApiDocument = {
  openapi: '3.1.0',
  info: {
    title: 'Task API Express',
    version: env.APP_VERSION,
    description: 'API de tareas con JWT, roles y MongoDB Atlas',
  },
  servers: [{ url: env.PUBLIC_API_URL, description: env.NODE_ENV === 'production' ? 'Producción' : 'Local' }],
  tags: [{ name: 'Health' }, { name: 'Auth' }, { name: 'Tasks' }],
  paths: {
    '/health': { get: { tags: ['Health'], summary: 'Salud HTTP',
      responses: { '200': { description: 'Disponible', ...json(ref('Health')) } } } },
    '/health/database': { get: { tags: ['Health'], summary: 'Salud de MongoDB',
      responses: { '200': { description: 'Conectada', ...json(ref('DatabaseHealth')) }, '503': error(503) } } },
    '/api/auth/register': { post: { tags: ['Auth'], summary: 'Registrar usuario',
      requestBody: { required: true, ...json(ref('RegisterInput')) },
      responses: { '201': { description: 'Registrado', ...json(ref('UserEnvelope')) },
        '409': error(409), '415': error(415), '422': error(422), '429': error(429) } } },
    '/api/auth/login': { post: { tags: ['Auth'], summary: 'Iniciar sesión',
      requestBody: { required: true, ...json(ref('LoginInput')) },
      responses: { '200': { description: 'Sesión creada', ...json(ref('LoginEnvelope')) },
        '401': error(401), '415': error(415), '422': error(422), '429': error(429) } } },
    '/api/auth/me': { get: { tags: ['Auth'], summary: 'Identidad actual', security,
      responses: { '200': { description: 'Identidad', ...json(ref('UserEnvelope')) }, '401': error(401) } } },
    '/api/tasks': {
      get: { tags: ['Tasks'], summary: 'Listado con paginación y filtros', security,
        parameters: [
          { $ref: '#/components/parameters/Page' }, { $ref: '#/components/parameters/Limit' },
          { $ref: '#/components/parameters/Status' }, { $ref: '#/components/parameters/Search' },
          { $ref: '#/components/parameters/SortBy' }, { $ref: '#/components/parameters/Order' },
        ],
        responses: { '200': { description: 'Listado', ...json(ref('TaskListResult')) }, ...taskResponses } },
      post: { tags: ['Tasks'], summary: 'Crear tarea', security,
        requestBody: { required: true, ...json(ref('CreateTaskInput')) },
        responses: { '201': { description: 'Creada', ...json(ref('TaskEnvelope')) }, ...taskResponses, '415': error(415) } },
    },
    '/api/tasks/{id}': {
      parameters: [{ $ref: '#/components/parameters/TaskId' }],
      get: { tags: ['Tasks'], summary: 'Obtener tarea', security,
        responses: { '200': { description: 'Tarea', ...json(ref('TaskEnvelope')) },
          ...taskResponses, '404': error(404) } },
      patch: { tags: ['Tasks'], summary: 'Editar tarea', security,
        requestBody: { required: true, ...json(ref('UpdateTaskInput')) },
        responses: { '200': { description: 'Actualizada', ...json(ref('TaskEnvelope')) },
          ...taskResponses, '404': error(404), '415': error(415) } },
      delete: { tags: ['Tasks'], summary: 'Eliminar tarea (admin)', security,
        responses: { '204': { description: 'Eliminada' }, ...taskResponses, '403': error(403), '404': error(404) } },
    },
    '/api/tasks/{id}/complete': { patch: { tags: ['Tasks'],
      summary: 'Completar tarea', security, parameters: [{ $ref: '#/components/parameters/TaskId' }],
      responses: { '200': { description: 'Completada', ...json(ref('TaskEnvelope')) }, ...taskResponses, '404': error(404) } } },
  },
  components: {
    securitySchemes: { bearerAuth: { type: 'http', scheme: 'bearer', bearerFormat: 'JWT' } },
    parameters: {
      TaskId: { in: 'path', name: 'id', required: true, schema: { type: 'string', pattern: '^[a-fA-F0-9]{24}$' } },
      Page: { in: 'query', name: 'page', schema: { type: 'integer', minimum: 1, default: 1 } },
      Limit: { in: 'query', name: 'limit', schema: { type: 'integer', minimum: 1, maximum: 100, default: 10 } },
      Status: { in: 'query', name: 'status', schema: { type: 'string', enum: ['pending', 'completed'] } },
      Search: { in: 'query', name: 'search', schema: { type: 'string', maxLength: 80 } },
      SortBy: { in: 'query', name: 'sortBy', schema: { type: 'string', enum: ['title','status','createdAt','updatedAt'] } },
      Order: { in: 'query', name: 'order', schema: { type: 'string', enum: ['asc','desc'] } },
    },
    schemas: {
      Health: { type: 'object', required: ['data'], properties: { data: { type: 'object', required: ['status', 'version', 'environment'], properties: { status: { type: 'string', const: 'up' }, version: { type: 'string' }, environment: { type: 'string' } } } } },
      DatabaseHealth: { type: 'object', required: ['data'], properties: { data: { type: 'object', properties: { status: { type: 'string', enum: ['up', 'down'] } } } } },
      User: { type: 'object', required: ['id','name','email','role','createdAt','updatedAt'],
        properties: { id: { type: 'string' }, name: { type: 'string' }, email: { type: 'string',format:'email' },
          role: { type: 'string', enum: ['user','admin'] }, createdAt: { type: 'string',format:'date-time' },
          updatedAt: { type: 'string',format:'date-time' } } },
      Task: { type: 'object', required: ['id','title','status','createdAt','updatedAt'],
        properties: { id: { type: 'string' }, title: { type: 'string' },
          status: { type: 'string', enum: ['pending','completed'] },
          createdAt: { type: 'string',format:'date-time' }, updatedAt: { type: 'string',format:'date-time' } } },
      RegisterInput: { type: 'object', additionalProperties: false, required:['name','email','password'],
        properties: { name: {type:'string',minLength:2,maxLength:80}, email:{type:'string',format:'email'},
          password:{type:'string',format:'password',minLength:8} } },
      LoginInput: { type: 'object', required:['email','password'], additionalProperties:false,
        properties: {email:{type:'string',format:'email'},password:{type:'string',format:'password'}} },
      CreateTaskInput: { type:'object',required:['title'],properties:{title:{type:'string',maxLength:120}} },
      UpdateTaskInput: { type:'object',additionalProperties:false,minProperties:1,
        properties:{title:{type:'string',maxLength:120},status:{type:'string',enum:['pending','completed']}} },
      ErrorEnvelope: {type:'object',required:['error'],properties:{error:{type:'object',
        properties:{code:{type:'string'},message:{type:'string'},requestId:{type:'string'}}}}},
      UserEnvelope: {type:'object',required:['data'],properties:{data:{type:'object',properties:{user:ref('User')}}}},
      LoginEnvelope: {type:'object',required:['data'],properties:{data:{type:'object',properties:{
        user:ref('User'),accessToken:{type:'string'},tokenType:{type:'string',const:'Bearer'},expiresIn:{type:'string'}}}}},
      TaskEnvelope: {type:'object',required:['data'],properties:{data:ref('Task')}},
      TaskListResult: {type:'object',required:['data','meta'],properties:{
        data:{type:'array',items:ref('Task')},meta:{type:'object',properties:{
          page:{type:'integer'},limit:{type:'integer'},total:{type:'integer'},
          totalPages:{type:'integer'},hasNextPage:{type:'boolean'},hasPreviousPage:{type:'boolean'}}}}},
    },
  },
};
